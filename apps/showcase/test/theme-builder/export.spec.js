import { describe, expect, it } from 'vitest';
import { definePreset } from '@openvue/themes';
import Aura from '@openvue/themes/aura';
import Material from '@openvue/themes/material';
import Nide from '@openvue/themes/nide';
import Nora from '@openvue/themes/nora';
import { isEqual } from '../../service/designer/diff';
import { SCHEMA_VERSION, THEME_FORMAT } from '../../service/designer/document';
import { importThemeObject } from '../../service/designer/importer';
import { applySharedRemovals, decodeShare, encodeShare } from '../../service/designer/share';
import { toAgentPrompt, toDesignerPayload, toExportFiles, toNuxtConfig, toNuxtThemeSource, toThemeCss, toThemeSource, toVueSetup } from '../../service/theme/export';
import { buildPresetExt } from '../../service/theme/compile';
import { PRESETS, presetRecipe } from '../../service/theme/recipe';

const BASES = { Aura, Material, Nide, Nora };

function preset(name) {
    const found = PRESETS.find((item) => item.name === name);
    const recipe = presetRecipe(found);
    const base = BASES[recipe.base];

    return { name: found.name + ' Theme', settings: recipe, base, compiled: definePreset(base, buildPresetExt(recipe, base)) };
}

function evaluateNuxtConfig(source) {
    return new Function('defineNuxtConfig', source.replace('export default ', 'return '))((config) => config);
}

describe('theme-builder/export', () => {
    describe('toThemeSource', () => {
        it('emits a diff against the base, credited to the builder', () => {
            const { name, settings, base, compiled } = preset('Garage');
            const source = toThemeSource(settings, name, base, compiled);

            expect(name).toBe('Garage Theme');
            expect(source).toContain('generated by the OpenVue Theme Builder.');
            expect(source).not.toContain('Theme Designer');
            expect(source).toContain("import Nora from '@openvue/themes/nora';");
            expect(source).toContain('export const GarageTheme = definePreset(Nora, overrides);');
            expect(source).toContain('font-family: Space Grotesk');
            expect(source).toContain("md: '0'");
        });
    });

    describe('toThemeCss', () => {
        it('loads the font and sets the root size', () => {
            const css = toThemeCss({ font: 'Figtree', scale: 15 });

            expect(css).toContain("@import url('https://fonts.googleapis.com/css2?family=Figtree:wght@400;500;600;700&display=swap');");
            expect(css).toContain('font-size: 15px;');
            expect(css).toContain('font-family: "Figtree", sans-serif;');
        });

        it('maps the site Inter build to the published family name', () => {
            const css = toThemeCss({ font: 'Inter var', scale: 14 });

            expect(css).toContain('family=Inter:wght@');
            expect(css).toContain('font-family: "Inter", sans-serif;');
        });

        it('uses the URL the page resolved, with the weights the family has', () => {
            const fontUrl = 'https://fonts.googleapis.com/css2?family=Lobster:wght@400&display=swap';

            const { name, settings, base, compiled } = preset('Garage');
            const files = toExportFiles({ ...settings, font: 'Lobster' }, name, base, compiled, { fontUrl });

            expect(toThemeCss({ font: 'Lobster', scale: 14 }, { fontUrl })).toContain("@import url('" + fontUrl + "');");
            expect(files.vue[2].code).toContain("@import url('" + fontUrl + "');");
            expect(files.nuxt[2].code).toContain("@import url('" + fontUrl + "');");
        });

        it('encodes multi-word families the way Google Fonts expects', () => {
            expect(toThemeCss({ font: 'Plus Jakarta Sans', scale: 14 })).toContain('family=Plus+Jakarta+Sans:wght@400;500;600;700');
        });
    });

    describe('toVueSetup', () => {
        it('installs the preset and sets the input variant only when it differs', () => {
            const outlined = toVueSetup({ input: 'outlined' }, 'Sharp Harbor');
            const filled = toVueSetup({ input: 'filled' }, 'Bright Plum');

            expect(outlined).toContain("import SharpHarbor from './theme';");
            expect(outlined).not.toContain('inputVariant');
            expect(filled).toContain("preset: BrightPlum\n    },\n    inputVariant: 'filled'\n});");
        });

        it('turns the ripple on beside the input variant', () => {
            expect(toVueSetup({ input: 'filled', ripple: true }, 'Plum')).toContain("preset: Plum\n    },\n    inputVariant: 'filled',\n    ripple: true\n});");
            expect(toNuxtConfig({ input: 'outlined', ripple: true })).toContain('options: {\n            ripple: true\n        }');
        });

        // `import App from './theme'` beside `import App from './App.vue'` would not parse.
        it.each([['App'], ['OpenVue'], ['open vue']])('renames a theme called %s away from the setup’s own imports', (name) => {
            const setup = toVueSetup({ input: 'outlined' }, name);
            const imports = setup.match(/^import (\w+) from/gm);

            expect(new Set(imports).size).toBe(imports.length);
            expect(setup).toMatch(/import \w+Theme from '\.\/theme';/);
        });
    });

    describe('Nuxt', () => {
        it('wraps the preset as the theme configuration the module imports', () => {
            const { name, settings, base, compiled } = preset('Loft');
            const source = toNuxtThemeSource(settings, name, base, compiled);

            expect(source).toContain("import Nide from '@openvue/themes/nide';");
            expect(source.endsWith('export default {\n    preset: LoftTheme\n};\n')).toBe(true);
        });

        // The code generator renames these so they do not shadow the base import or a global.
        it.each([
            ['Nide', 'NideTheme'],
            ['Preset', 'PresetTheme'],
            ['Reflect', 'ReflectTheme']
        ])('wraps a theme called %s under its renamed identifier', (name, identifier) => {
            const { settings, base, compiled } = preset('Loft');
            const source = toNuxtThemeSource(settings, name, base, compiled);

            expect(source.endsWith(`export default {\n    preset: ${identifier}\n};\n`)).toBe(true);
        });

        it('generates a config that evaluates to the module options', () => {
            expect(evaluateNuxtConfig(toNuxtConfig({ input: 'outlined' }))).toEqual({
                modules: ['@openvue/nuxt-module'],
                css: ['~/assets/css/theme.css'],
                primevue: { importTheme: { from: '@/themes/theme.js' } }
            });

            expect(evaluateNuxtConfig(toNuxtConfig({ input: 'filled' })).primevue).toEqual({ importTheme: { from: '@/themes/theme.js' }, options: { inputVariant: 'filled' } });
        });
    });

    it('offers three files per framework', () => {
        const { name, settings, base, compiled } = preset('Portico');
        const files = toExportFiles(settings, name, base, compiled);

        expect(files.vue.map((file) => file.name)).toEqual(['src/theme.js', 'src/main.js', 'src/theme.css']);
        expect(files.nuxt.map((file) => file.name)).toEqual(['themes/theme.js', 'nuxt.config.ts', 'assets/css/theme.css']);
    });

    describe('toAgentPrompt', () => {
        function instructions(prompt) {
            return prompt
                .replace(/```[\s\S]*?```/g, '')
                .split('\n')
                .filter((line) => line.trim() && !/^`[^`]+`$/.test(line));
        }

        it('gives the two theme files and the one setup change', () => {
            const { name, settings, base, compiled } = preset('Atelier');
            const [theme, setup, css] = toExportFiles(settings, name, base, compiled).vue;
            const prompt = toAgentPrompt([theme, setup, css], { framework: 'vue', recipe: settings, name });

            expect(instructions(prompt)).toEqual([
                'Add the OpenVue theme "Atelier Theme" to this project. It needs `openvue` and `@openvue/themes`.',
                '1. Save the two files below as `src/theme.js` and `src/theme.css`. In a TypeScript project, name the first `src/theme.ts`; the code stays the same.',
                "2. Where the app calls `app.use(OpenVue, ...)`, import `./theme.css` and `AtelierTheme` from `./theme`, then set `theme: { preset: AtelierTheme }`, `inputVariant: 'filled'` and `ripple: true`. Keep the other options as they are."
            ]);
            expect(prompt).toContain('`src/theme.js`\n\n```js\n' + theme.code.trimEnd() + '\n```');
            expect(prompt).toContain('`src/theme.css`\n\n```css\n' + css.code.trimEnd() + '\n```');
            // The complete setup would invite the agent to replace the project's own.
            expect(prompt).not.toContain('createApp');
        });

        it('points a Nuxt project at the theme from its config, and names Nide', () => {
            const { name, settings, base, compiled } = preset('Loft');
            const prompt = toAgentPrompt(toExportFiles(settings, name, base, compiled).nuxt, { framework: 'nuxt', recipe: settings, name });

            expect(instructions(prompt)).toEqual([
                'Add the OpenVue theme "Loft Theme" to this project. It needs `@openvue/nuxt-module` and `@openvue/themes`.',
                '1. Save the two files below as `themes/theme.js` and `assets/css/theme.css`. In a TypeScript project, name the first `themes/theme.ts` and use that path in step 2; the code stays the same.',
                "2. In `nuxt.config.ts`, add `'~/assets/css/theme.css'` to `css` and set `primevue.importTheme` to `{ from: '@/themes/theme.js' }`. Keep the other options as they are.",
                'It is built on the Nide preset. If `@openvue/themes/nide` does not resolve, update `@openvue/themes` rather than switching to another preset.'
            ]);
            expect(prompt).not.toContain('defineNuxtConfig');
        });

        it('adds the input variant and ripple to the Nuxt module options', () => {
            const { name, settings, base, compiled } = preset('Atelier');
            const prompt = toAgentPrompt(toExportFiles(settings, name, base, compiled).nuxt, { framework: 'nuxt', recipe: settings, name });

            expect(prompt).toContain("and add `inputVariant: 'filled'` and `ripple: true` to `primevue.options`.");
        });
    });

    describe('designer handoff', () => {
        it.each([['Garage'], ['Atelier'], ['Loft'], ['Portico'], ['Pavilion']])('%s arrives in the designer unchanged', async (id) => {
            const { name, settings, base, compiled } = preset(id);
            const decoded = await decodeShare(await encodeShare(toDesignerPayload(settings, name, base, compiled)));

            expect(decoded.ok).toBe(true);

            const { diff, removed, config } = decoded.payload;
            const imported = importThemeObject({
                format: THEME_FORMAT,
                schemaVersion: SCHEMA_VERSION,
                name: decoded.payload.name,
                base: decoded.payload.base,
                preset: applySharedRemovals(definePreset(base, diff), removed),
                config
            });

            expect(imported.ok).toBe(true);
            expect(imported.validation.canExport).toBe(true);
            expect(imported.document.base).toBe(settings.base);
            expect(imported.document.config).toEqual({ font_family: settings.font, font_size: settings.scale + 'px' });
            expect(isEqual(imported.document.preset, JSON.parse(JSON.stringify(compiled)))).toBe(true);
        });
    });
});
